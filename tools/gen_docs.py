#!/usr/bin/env python3
"""Write the reference docs from the code, so they can never drift from it.

    python3 tools/gen_docs.py           (re)write the files below
    python3 tools/gen_docs.py --check   exit 1 if any file is out of date (used by the tests and CI)

Writes the same three files to docs/reference/ (for people) and skills/pcbtestkit/references/ (for AI
agents; a skill folder must be self-contained):
  cli.md     every command and option, from the argparse parser
  tools.md   every agent/MCP tool with its arguments, from the tool registry
  config.md  every pcbtestkit.json key with its default, from config.DEFAULTS
"""
import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
os.environ["COLUMNS"] = "100"          # argparse wraps usage to the terminal width; keep output stable

TARGETS = [os.path.join(ROOT, "docs", "reference"), os.path.join(ROOT, "skills", "pcbtestkit", "references")]
HEADER = "<!-- Generated by tools/gen_docs.py from the code. Do not edit by hand. -->\n\n"

CONFIG_NOTES = {
    "fab_profile": "Baseline manufacturing limits: standard | advanced | conservative. A technology class (tech) overrides it.",
    "fab_overrides": "Individual fab limits in mm, e.g. {\"min_track\": 0.1}.",
    "tech": "Fab class system and the class you order; extra class checks; board context (finish, copper, mask colour).",
    "supply": "How the tester powers the board: net, voltage, current limit and the expected idle-current window.",
    "nets": "Per-net expectations: nominal + tolerance_pct or min/max (volts), kind, test: false to skip.",
    "testplan": "Probe side, pogo family and mounting, signal policy, channel budget, ADC range, timing.",
    "fixture": "Fixture PCB outline, margins, N x M panel, mounting holes, dividers, routing (tracks, vias, clearance).",
    "batch": "Boards per batch: one fixture site per board, jigs that hold them all (fewer per jig if the printer bed "
             "is too small); column count, site spacing, printer bed.",
    "program": "Programming headers (auto-detected SWD/JTAG/ISP/ICSP/UPDI/UART-boot or by ref), the fixture's programming "
               "connector per board (copy of the header or a standard pinout) and the runner's flash command.",
    "jig": "Solder-jig parts (auto = all THT), pocket clearances and depths, part heights by ref.",
    "analysis": "Waivers, ignored checks and thresholds for the weak-point analysis.",
    "video": "Explainer video: real 3D animation on/off, frame rate, size, parallel renders, render quality.",
    "outputs": "Which files a run writes by default.",
}


def _flag(a) -> str:
    return ", ".join("`%s`" % o for o in a.option_strings) if a.option_strings else "`%s`" % a.dest


def cli_md() -> str:
    from pcbtestkit.cli import build_parser
    ap = build_parser()
    sub = next(a for a in ap._actions if isinstance(a, argparse._SubParsersAction))
    out = [HEADER, "# CLI reference\n\n",
           "Run `pcbtestkit <command> --help` for the same text. Without a pip install use `python3 -m pcbtestkit` "
           "with the repository (or the installed plugin folder) on `PYTHONPATH`. AI agents: start with "
           "`pcbtestkit guide`.\n\n",
           "| Command | Purpose |\n|---|---|\n"]
    helps = {c.dest: c.help for c in sub._choices_actions}
    for name in sub.choices:
        out.append("| `%s` | %s |\n" % (name, helps.get(name, "")))
    for name, p in sub.choices.items():
        out.append("\n## `pcbtestkit %s`\n\n%s\n\n```text\n%s```\n\n" % (name, helps.get(name, ""), p.format_usage().replace("usage: ", "")))
        rows = []
        for a in p._actions:
            if isinstance(a, argparse._HelpAction):
                continue
            extra = []
            if a.choices:
                extra.append("one of: " + ", ".join(str(c) for c in a.choices))
            if a.default not in (None, False, argparse.SUPPRESS) and a.option_strings:
                extra.append("default: %s" % a.default)
            if a.option_strings and a.nargs is None and not isinstance(a, (argparse._StoreTrueAction, argparse._AppendAction)) and not a.choices:
                pass
            text = (a.help or "").replace("|", "\\|")
            if extra:
                text = (text + " (" + "; ".join(extra) + ")").strip()
            rows.append("| %s | %s |\n" % (_flag(a), text))
        if rows:
            out.append("| Argument | Meaning |\n|---|---|\n" + "".join(rows))
    return "".join(out)


def _type(v) -> str:
    if "enum" in v:
        return " \\| ".join(str(e) for e in v["enum"])
    t = v.get("type", "any")
    if isinstance(t, list):
        t = " \\| ".join(t)
    if t == "array" and isinstance(v.get("items"), dict):
        it = v["items"]
        t = "array of %s" % (it.get("type") or "object")
    return t


def tools_md() -> str:
    from pcbtestkit.agent import PROFILES, TOOLS, profile_tools
    core = set(profile_tools("core"))
    out = [HEADER, "# Tool reference (agent API and MCP)\n\n",
           "The same %d tools are available through `pcbtestkit api <tool> --args '<json>' --compact`, the MCP server "
           "(`pcbtestkit mcp`) and Python (`pcbtestkit.agent.Workspace.call`). Every call returns one JSON object with "
           "`\"ok\": true|false`; errors carry `code`, `message` and often `hint` or `did_you_mean`.\n\n" % len(TOOLS),
           "R = read-only, W = write (stored in `pcbtestkit.json` with an audit entry; `undo_last` reverts up to 20 writes). "
           "Every write accepts `rationale` (one sentence), `dry_run` (preview the effects) and `confirm` (needed after "
           "a `CONFIRM_REQUIRED` answer). Core = included in the MCP `core` profile (%s profiles: %s).\n\n"
           % ("tool", ", ".join(PROFILES)),
           "| Tool | R/W | Core | Summary |\n|---|---|---|---|\n"]
    for n, t in TOOLS.items():
        out.append("| [`%s`](#%s) | %s | %s | %s |\n" % (n, n, "R" if t["read_only"] else "W", "yes" if n in core else "",
                                                          t["description"].split(". ")[0].rstrip(".").replace("|", "\\|")))
    common = {"rationale", "dry_run", "confirm"}
    for n, t in TOOLS.items():
        sch = t["input_schema"]
        req = set(sch.get("required") or [])
        out.append("\n### %s\n\n%s\n\n" % (n, t["description"].replace("|", "\\|")))
        props = [(k, v) for k, v in (sch.get("properties") or {}).items() if k not in common]
        if not props:
            out.append("No arguments%s.\n" % ("" if t["read_only"] else " besides rationale/dry_run/confirm"))
            continue
        out.append("| Argument | Type | Description |\n|---|---|---|\n")
        for k, v in props:
            desc = (v.get("description") or "").replace("|", "\\|").replace("\n", " ")
            out.append("| `%s`%s | %s | %s |\n" % (k, " (required)" if k in req else "", _type(v), desc))
            items = v.get("items") if isinstance(v.get("items"), dict) else None
            if items and items.get("properties"):
                ireq = set(items.get("required") or [])
                for ik, iv in items["properties"].items():
                    idesc = (iv.get("description") or "").replace("|", "\\|")
                    out.append("| `%s[].%s`%s | %s | %s |\n" % (k, ik, " (required)" if ik in ireq else "", _type(iv), idesc))
    return "".join(out)


def config_md() -> str:
    from pcbtestkit.config import DEFAULTS, FAB_PROFILES, POGO_PROFILES
    out = [HEADER, "# Configuration reference (`pcbtestkit.json`)\n\n",
           "`pcbtestkit.json` sits next to the KiCad project and only holds what differs from the defaults below. "
           "The KiCad dialog, the CLI options and the AI write tools all edit this file (writes add an `_audit` entry). "
           "`pcbtestkit init <project>` writes a starting template. Commit it with the design.\n\n"]
    for k, v in DEFAULTS.items():
        out.append("## `%s`\n\n%s\n\n```json\n%s\n```\n\n" % (k, CONFIG_NOTES.get(k, ""), json.dumps({k: v}, indent=2)))
    out.append("## Fab profiles\n\nLimits (mm) behind `fab_profile`; a technology class replaces them.\n\n```json\n%s\n```\n\n"
               % json.dumps(FAB_PROFILES, indent=2))
    out.append("## Pogo families\n\nUsed by `testplan.pogo`; check drills against your pin's datasheet.\n\n```json\n%s\n```\n"
               % json.dumps(POGO_PROFILES, indent=2))
    return "".join(out)


def render() -> dict:
    return {"cli.md": cli_md(), "tools.md": tools_md(), "config.md": config_md()}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    docs = render()
    stale = []
    for d in TARGETS:
        for name, text in docs.items():
            path = os.path.join(d, name)
            cur = open(path, encoding="utf-8").read() if os.path.exists(path) else None
            if cur == text:
                continue
            if a.check:
                stale.append(os.path.relpath(path, ROOT))
            else:
                os.makedirs(d, exist_ok=True)
                with open(path, "w", encoding="utf-8") as fh:
                    fh.write(text)
                print("wrote", os.path.relpath(path, ROOT))
    if a.check:
        if stale:
            print("out of date (run python3 tools/gen_docs.py):\n  " + "\n  ".join(stale))
            return 1
        print("reference docs are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
